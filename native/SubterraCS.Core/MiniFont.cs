namespace SubterraCS.Core;

/// <summary>
/// A tiny 8×8 monospace font.  Only the characters the HUD actually
/// uses (digits, capital letters, a handful of punctuation).
/// Authored by hand so the native build has zero font dependencies.
/// </summary>
public static class MiniFont
{
    private static readonly byte[] Empty = new byte[8];

    /// <summary>Get the 8 row-bytes for the glyph of <paramref name="ch"/>.</summary>
    public static ReadOnlySpan<byte> Glyph(char ch)
    {
        if (ch >= 'a' && ch <= 'z') ch = (char)(ch - 32);
        return Glyphs.TryGetValue(ch, out var g) ? g : Empty;
    }

    // Each glyph is 8 bytes — one byte per row, MSB on the left.
    private static readonly Dictionary<char, byte[]> Glyphs = new()
    {
        [' '] = new byte[] { 0,0,0,0,0,0,0,0 },
        ['.'] = new byte[] { 0,0,0,0,0,0,0x18,0x18 },
